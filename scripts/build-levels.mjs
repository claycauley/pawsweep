// Pre-generates the levels so the game never has to run the (slow) generator.
// Run with: npm run levels:build   (slow, only needed when the generator or level count changes)
// Writes src/js/levels-data.js. Each level is stored as "row,row,...|solution|tier".
import { writeFileSync, existsSync } from "node:fs";
import { generate, tierFor } from "../src/js/difficulty.js";

const COUNT = 300;
const SIZES = { easy: 5, normal: 6, hard: 8, crazy: 10 }; // keep in sync with DIFFICULTIES in state.js ("crazy" is shown as "Wicked")

// Usage: npm run levels:build            -> regenerate every difficulty
//        npm run levels:build -- easy    -> regenerate only the named ones (others are kept)
const only = process.argv.slice(2).filter(k => SIZES[k]);
const dataUrl = new URL("../src/js/levels-data.js", import.meta.url);
const out = only.length && existsSync(dataUrl) ? structuredClone((await import(dataUrl.href)).LEVELS) : {};

for (const [key, n] of Object.entries(SIZES)) {
  if (only.length && !only.includes(key)) continue;
  const t0 = Date.now();
  out[key] = [];
  const total = COUNT;
  for (let L = 1; L <= total; L++) {
    // Same seed formula the game used for live generation
    const p = generate(n, L * 7919 + 101 + n * 104729, tierFor(L));
    out[key].push(`${p.regions.map(r => r.join("")).join(",")}|${p.sol.join("")}|${p.tier}`);
  }
  console.log(`${key}: ${total} levels in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
}

const js =
  `// GENERATED by scripts/build-levels.mjs. Do not edit by hand.\n` +
  `export const LEVEL_COUNT = ${COUNT};\n` +
  `export const LEVELS = ${JSON.stringify(out)};\n`;
writeFileSync(new URL("../src/js/levels-data.js", import.meta.url), js);
console.log("src/js/levels-data.js written");
